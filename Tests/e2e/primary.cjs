const qpUi=require('./ui-actions.cjs');
let ownedBrowser;
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/estju/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
 const browser=ownedBrowser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
 const page=await context.newPage();
 page.on('pageerror',e=>console.log('PAGE_ERROR',e.message));
 page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE_ERROR',m.text());});
 await page.goto((process.env.QP_BASE_URL||'http://127.0.0.1:5188'));
 await qpUi.click(page,{name:'Nueva plantilla'});
 await qpUi.label(page,'Título');await page.getByLabel('Título',{exact:true}).fill('Prueba E2E local');
 await qpUi.label(page,'Descripción');await page.getByLabel('Descripción',{exact:true}).fill('Datos ficticios de aceptación');
 await qpUi.label(page,'Texto de la plantilla');await page.getByLabel('Texto de la plantilla',{exact:true}).fill('Explica <tema> para <persona>.');
 await qpUi.click(page,{name:'Guardar plantilla',exact:true});
 await qpUi.click(page,{name:/Generar texto final/});await page.locator('.notice.error').waitFor();if(await page.getByTestId('compiled').count())throw new Error('Missing fields compiled');await qpUi.label(page,'tema');await page.getByLabel('tema',{exact:true}).fill('SQLite');
 await qpUi.label(page,'persona');await page.getByLabel('persona',{exact:true}).fill('principiante');
 await qpUi.click(page,{name:'Generar texto final',exact:false});
 await page.getByTestId('compiled').waitFor();
 const rendered=await page.getByTestId('compiled').innerText();
 if(rendered!=='Explica SQLite para principiante.')throw new Error('Wrong render '+rendered);
 await qpUi.click(page,{name:'Copiar prompt',exact:true});
 await page.getByText('Copiado al portapapeles.',{exact:true}).waitFor();
 const clipboard=await page.evaluate(()=>navigator.clipboard.readText());
 if(clipboard!==rendered)throw new Error('Wrong clipboard');
 await page.screenshot({path:'.playwright/primary-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'.playwright/primary-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw new Error('Mobile overflow');
 console.log(JSON.stringify({browser:await browser.version(),rendered,clipboard,overflow,status:'PASS_PRIMARY'},null,2));
 await browser.close();
})().catch(async e=>{console.error(e);if(ownedBrowser)await ownedBrowser.close();process.exitCode=1;});
